import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sourceUrl = new URL('./client.mjs', import.meta.url);
const outputUrl = new URL('./client.js', import.meta.url);
const packageName = '@dotdrelle/dsh-llm-wiki';
let source = await readFile(sourceUrl, 'utf8');

const reactImport = "import { createElement as h, useEffect, useState } from 'react';";
if (!source.includes(reactImport)) throw new Error('Expected React import was not found in client.mjs.');
source = source.replace(reactImport, '');
source = source.replace('export const inject =', 'const inject =');
source = source.replace('export function apply(ctx)', 'function apply(ctx)');
if (/^\s*(?:export|import)\s/gm.test(source)) {
  throw new Error('client.mjs contains an import/export that build-client.mjs does not bundle.');
}

const bundle = `/* Generated by build-client.mjs from client.mjs. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory(require) {
    const { createElement: h, useEffect, useState } = require('react');
${source.split('\n').map((line) => line ? `    ${line}` : '').join('\n')}
    return { apply, inject };
  },
});
`;

await writeFile(outputUrl, bundle);
